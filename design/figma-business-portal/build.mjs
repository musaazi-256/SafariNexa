// Shares tokens, components and icons with the admin plugin (../figma-admin-portal/src/lib.js).
import { readFileSync, writeFileSync } from "node:fs";
const own = new URL("./src/", import.meta.url);
const shared = new URL("../figma-admin-portal/src/", import.meta.url);
const logo = readFileSync(new URL("logo.svg", shared), "utf8").replace(/\s+/g, " ").trim();
const files = [[shared, "lib.js"], [own, "common.js"], [own, "shell.js"], [own, "screens-a.js"], [own, "screens-b.js"], [own, "screens-c.js"], [own, "main.js"]];
const parts = files.map(([d, f]) => `// ---- ${f}\n` + readFileSync(new URL(f, d), "utf8"));
const out = `// GENERATED by build.mjs — edit src/*.js (and ../figma-admin-portal/src/lib.js) instead.\n"use strict";\nconst LOGO_SVG = ${JSON.stringify(logo)};\n` + parts.join("\n");
writeFileSync(new URL("./code.js", import.meta.url), out);
console.log("code.js written", out.length, "bytes");
