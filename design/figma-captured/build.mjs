// Builds the three captured-design plugins (admin, business, customer) from
// src/plugin.ts:  node design/figma-captured/build.mjs
// Each gets its own manifest and code.js pointing at its bundle on GitHub main.
import { createRequire } from "node:module";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const ts = createRequire(here + "../../Prototype/package.json")("typescript");
const RAW = "https://raw.githubusercontent.com/musaazi-256/SafariNexa/main/design/handoff/";
const PLUGINS = {
  admin: "SafariNexa Admin · captured designs",
  business: "SafariNexa Business · captured designs",
  customer: "SafariNexa Customer · captured designs",
};

const src = readFileSync(here + "src/plugin.ts", "utf8");
const logo = readFileSync(here + "src/logo.svg", "utf8").trim();
const { outputText, diagnostics } = ts.transpileModule(src, { compilerOptions: { target: ts.ScriptTarget.ES2017, module: ts.ModuleKind.None, removeComments: false }, reportDiagnostics: true });
if (diagnostics.length) throw new Error(diagnostics.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n")).join("\n"));

for (const [portal, name] of Object.entries(PLUGINS)) {
  const dir = here + portal + "/";
  mkdirSync(dir, { recursive: true });
  const header = `// Generated by design/figma-captured/build.mjs from src/plugin.ts. Don't edit by hand.\nconst PORTAL = ${JSON.stringify(portal)};\nconst SOURCE = ${JSON.stringify(RAW + portal + "/" + portal + "-captured.json")};\nconst LOGO = ${JSON.stringify(logo)};\n`;
  writeFileSync(dir + "code.js", header + outputText);
  writeFileSync(
    dir + "manifest.json",
    JSON.stringify(
      {
        name,
        id: "safarinexa-" + portal + "-captured",
        api: "1.0.0",
        main: "code.js",
        editorType: ["figma"],
        documentAccess: "dynamic-page",
        networkAccess: { allowedDomains: ["https://raw.githubusercontent.com"], reasoning: "Loads the captured designs committed to the SafariNexa repository on GitHub." },
      },
      null,
      2,
    ) + "\n",
  );
  console.log("built", portal, (outputText.length / 1024).toFixed(0) + " KB");
}
