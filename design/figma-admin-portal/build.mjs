import { readFileSync, writeFileSync } from "node:fs";
const dir = new URL("./src/", import.meta.url);
const logo = readFileSync(new URL("logo.svg", dir), "utf8").replace(/\s+/g, " ").trim();
const parts = ["lib.js", "shell.js", "screens-a.js", "screens-b.js", "main.js"].map(f => `// ---- ${f}\n` + readFileSync(new URL(f, dir), "utf8"));
const out = `// GENERATED by build.mjs — edit src/*.js instead.\n"use strict";\nconst LOGO_SVG = ${JSON.stringify(logo)};\n` + parts.join("\n");
writeFileSync(new URL("./code.js", import.meta.url), out);
console.log("code.js written", out.length, "bytes");
